export interface LexiconVerb {
  inf: string;
  en: string;
  level: VerbLevel;
  group: StemGroup;
  present: string[];
  gerund: string;
  participle: string;
  /** A one-line pattern note that stands in for the hand-written memory tricks. */
  trick: string;
}

function trickFor(inf: string, group: StemGroup, present: string[]): string {
  const type = inf.slice(-2);
  switch (group) {
    case 'regular': return `Regular -${type} verb: keep the stem "${inf.slice(0, -2)}-" and add the endings.`;
    case 'stem-e-ie': case 'stem-o-ue': case 'stem-e-i': case 'stem-u-ue': return `Boot verb: yo, tú, él and ellos change the stem (${present[0]}, ${present[1]}…); nosotros and vosotros keep it (${present[3]}).`;
    case 'irregular-yo': return `Only the yo form is irregular: ${present[0]}. The rest is regular.`;
    case 'irregular': return `Irregular: learn the yo form (${present[0]}) and the pattern of its base verb.`;
  }
}

export const LEXICON: LexiconVerb[] = ENTRIES.map(([inf, en, level, o = {}]) => {
  const baseGroup: StemGroup = o.group ?? 'regular';
  const present = o.present ?? regularPresentForms(inf, baseGroup, o.yo);
  const yoIrregular = !!o.yo || (!o.present && !!patternYo(inf)) || /guir$/.test(inf);
  // -uir verbs (construyo) and verbs with an explicit present (envío, atenúo) deviate from the regular paradigm in the whole boot.
  const wholeBoot = (/uir$/.test(inf) && !/guir$/.test(inf)) || (!!o.present && baseGroup === 'regular');
  const group: StemGroup = baseGroup === 'regular' && wholeBoot ? 'irregular' : baseGroup === 'regular' && yoIrregular ? 'irregular-yo' : baseGroup;
  return { inf, en, level, group, present, gerund: o.gerund ?? regularGerund(inf, baseGroup), participle: o.participle ?? regularParticiple(inf), trick: trickFor(inf, group, present) };
});
